export function getFileIcon(type, size = 16) {
  switch (type) {
    case 'pdf':
      return icon('fileText', size, 'text-red-500');
    case 'xlsx':
    case 'csv':
      return icon('table', size, 'text-emerald-500');
    case 'image':
      return icon('image', size, 'text-blue-500');
    case 'transcript':
      return icon('bookOpen', size, 'text-amber-500');
    case 'docx':
    case 'txt':
    default:
      return icon('file', size, 'text-slate-400');
  }
}
